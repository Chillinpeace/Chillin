import express from 'express';
import crypto from 'crypto';
import PDFDocument from 'pdfkit';
import { query } from './database.js';

const router = express.Router();
const SESSION_COOKIE = 'peacely_session';
const hash = (v) => crypto.createHash('sha256').update(String(v)).digest('hex');
const clean = (v) => String(v ?? '').trim();
const num = (v) => Number(v || 0);

function cookies(req) {
  const out = {};
  for (const part of String(req.headers.cookie || '').split(';')) {
    const i = part.indexOf('=');
    if (i < 0) continue;
    const key = part.slice(0, i).trim();
    const value = part.slice(i + 1).trim();
    try { out[key] = decodeURIComponent(value); } catch { out[key] = value; }
  }
  return out;
}

async function ownerFromRequest(req) {
  const token = cookies(req)[SESSION_COOKIE];
  if (!token) return null;
  const r = await query(
    `SELECT o.id,o.name,o.email
     FROM sessions s JOIN owners o ON o.id=s.owner_id
     WHERE s.token_hash=$1 AND s.expires_at>CURRENT_TIMESTAMP
     LIMIT 1`,
    [hash(token)],
  );
  return r.rows[0] || null;
}

async function ensureVerificationSchema() {
  await query(`
    CREATE TABLE IF NOT EXISTS tenant_verifications (
      id SERIAL PRIMARY KEY,
      owner_id INTEGER NOT NULL,
      tenant_id INTEGER NOT NULL,
      source VARCHAR(40) NOT NULL DEFAULT 'manual',
      status VARCHAR(40) NOT NULL DEFAULT 'pending',
      consent_at TIMESTAMPTZ,
      verified_at TIMESTAMPTZ,
      reference_id VARCHAR(160) DEFAULT '',
      masked_document VARCHAR(80) DEFAULT '',
      created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
      updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
    );
    ALTER TABLE tenant_verifications ADD COLUMN IF NOT EXISTS source VARCHAR(40) NOT NULL DEFAULT 'manual';
    ALTER TABLE tenant_verifications ADD COLUMN IF NOT EXISTS status VARCHAR(40) NOT NULL DEFAULT 'pending';
    ALTER TABLE tenant_verifications ADD COLUMN IF NOT EXISTS consent_at TIMESTAMPTZ;
    ALTER TABLE tenant_verifications ADD COLUMN IF NOT EXISTS verified_at TIMESTAMPTZ;
    ALTER TABLE tenant_verifications ADD COLUMN IF NOT EXISTS reference_id VARCHAR(160) DEFAULT '';
    ALTER TABLE tenant_verifications ADD COLUMN IF NOT EXISTS masked_document VARCHAR(80) DEFAULT '';
    ALTER TABLE tenant_verifications ADD COLUMN IF NOT EXISTS updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP;
    CREATE INDEX IF NOT EXISTS idx_tenant_verifications_owner_tenant ON tenant_verifications(owner_id,tenant_id);
  `);
}

function safeFilePart(v) {
  return clean(v).replace(/[^a-z0-9_-]+/gi, '-').replace(/^-+|-+$/g, '') || 'tenant';
}

function header(doc, title, ownerName) {
  doc.font('Helvetica-Bold').fontSize(18).text(title);
  doc.font('Helvetica').fontSize(9).fillColor('#555').text('Generated by Peacely');
  doc.fillColor('#111').moveDown(0.5);
  doc.fontSize(9).text(`Owner / Manager: ${ownerName || '-'}`);
  doc.moveDown(0.5);
}

function section(doc, title) {
  doc.moveDown(0.5);
  doc.font('Helvetica-Bold').fontSize(11).text(title);
  doc.moveTo(50, doc.y + 3).lineTo(545, doc.y + 3).strokeColor('#bbb').stroke();
  doc.strokeColor('#000').moveDown(0.4);
}

function field(doc, label, value) {
  doc.font('Helvetica-Bold').fontSize(9).text(label + ': ', { continued: true });
  doc.font('Helvetica').text(clean(value) || '-');
}

async function getTenant(ownerId, tenantId) {
  const r = await query(
    `SELECT t.id,t.name,t.phone,t.email,t.gender,t.id_proof_type,t.property_id,t.room_id,t.bed_id,
            t.monthly_rent,t.due_date,t.deposit_amount,t.move_in_date,t.move_out_date,t.status,
            p.name AS property_name,p.address AS property_address,
            r.room_number,b.bed_number
     FROM tenants t
     JOIN properties p ON p.id=t.property_id
     LEFT JOIN rooms r ON r.id=t.room_id
     LEFT JOIN beds b ON b.id=t.bed_id
     WHERE t.id=$1 AND p.owner_id=$2
     LIMIT 1`,
    [tenantId, ownerId],
  );
  return r.rows[0] || null;
}

router.get('/tenant-verification/status', async (req, res) => {
  const owner = await ownerFromRequest(req);
  if (!owner) return res.status(401).json({ success:false, error:'Authentication required.' });
  await ensureVerificationSchema();
  const configured = Boolean(process.env.DIGILOCKER_CLIENT_ID && process.env.DIGILOCKER_CLIENT_SECRET);
  res.json({
    success:true,
    configured,
    status: configured ? 'ready_for_consent' : 'requester_approval_required',
    message: configured
      ? 'DigiLocker requester credentials are configured.'
      : 'Peacely must first be approved as a DigiLocker/API Setu Requester before production document access can be enabled.',
    onboarding_url: 'https://partners.apisetu.gov.in/signup',
  });
});

router.post('/tenant-verification/start', async (req, res) => {
  const owner = await ownerFromRequest(req);
  if (!owner) return res.status(401).json({ success:false, error:'Authentication required.' });
  await ensureVerificationSchema();

  const tenantId = num(req.body?.tenant_id);
  const tenant = await getTenant(owner.id, tenantId);
  if (!tenant) return res.status(404).json({ success:false, error:'Tenant not found.' });

  await query(
    `INSERT INTO tenant_verifications(owner_id,tenant_id,source,status,consent_at)
     VALUES($1,$2,'digilocker','consent_pending',CURRENT_TIMESTAMP)`,
    [owner.id, tenantId],
  );

  const configured = Boolean(process.env.DIGILOCKER_CLIENT_ID && process.env.DIGILOCKER_CLIENT_SECRET);
  res.json({
    success:true,
    configured,
    status: configured ? 'consent_required' : 'requester_approval_required',
    message: configured
      ? 'DigiLocker consent flow is ready to be connected to the approved Peacely requester credentials.'
      : 'DigiLocker integration is staged. Complete API Setu requester onboarding first; no Aadhaar data is queried or stored by this endpoint.',
    onboarding_url: 'https://partners.apisetu.gov.in/signup',
  });
});

